#!/usr/bin/env python3
"""Generate transparent lean-angle PNG frames for Apple Motion using multiple CPU cores.

Examples:
  python3 generate_lean_angle_resume.py data.csv
  python3 generate_lean_angle_resume.py data.csv --fps 60
  python3 generate_lean_angle_resume.py data.csv --fps 24 --workers 4
  python3 generate_lean_angle_resume.py data.csv --restart
  python3 generate_lean_angle_resume.py data.csv --adopt-existing

CSV headers: frame,lean_angle OR frame,value; frame is optional.
Negative lean moves the dot left; positive lean moves it right.

Uses multiprocessing (separate processes), not Python threads: drawing
and image processing are CPU/memory-intensive. Processes can run on several CPU
cores. By default it uses (logical CPU count + 1) workers.
4x AA at 1920x1080 uses substantial RAM per worker; consider --workers 2
or --workers 4 if automatic selection uses too much memory.

Skia draws and encodes PNGs by default, with native antialiasing (--aa 1).
Install requirements.txt. --backend pillow selects the original renderer
(default --aa 4) for compatible resumes or comparison. Skia AA>1 uses
Mitchell cubic downsampling, not Pillow LANCZOS. Backends preserve the
design but do not produce identical pixels; never mix their output frames.

PNG image files cannot encode an FPS; --fps specifies intended playback speed.

Pause: press Ctrl+C once. Workers finish their in-flight frames and exit.
Resume: run the same command; completed and valid PNGs are skipped.

A manifest remembers CSV content and rendering settings, preventing accidental
mixing of incompatible frames. Use --restart to discard previous rendered PNGs.
For a folder generated by an older script with no manifest, use --adopt-existing
to reuse its PNGs if you know the settings and data match.
"""

import argparse
import csv
import hashlib
import json
import math
import multiprocessing
import os
import re
import signal
import sys
import tempfile
import time
from concurrent.futures import FIRST_COMPLETED, ProcessPoolExecutor, wait
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

WIDTH = 1920
HEIGHT = 1080
FPS = 30
AA = 1
PILLOW_AA = 4

ARC_COLOR = (255, 255, 255, 180)
DOT_COLOR = (255, 255, 255, 255)
TEXT_COLOR = (255, 255, 255, 255)
ARC_WIDTH = 8
DOT_RADIUS = 16
ZERO_TICK_LENGTH = 30
ZERO_TICK_WIDTH = 5
FONT_SIZE = 170
FONT_PATH = "/System/Library/Fonts/Supplemental/Arial.ttf"

# Each process loads its font once, instead of reloading it for every PNG.
_WORKER_FONT = None
_WORKER_OUTPUT = None
_WORKER_WIDTH = None
_WORKER_HEIGHT = None
_WORKER_AA = None
_WORKER_SKIA = None


def load_font(size):
    for font_path in (
        FONT_PATH,
        "/System/Library/Fonts/Supplemental/Helvetica.ttc",
        "DejaVuSans.ttf",
    ):
        try:
            return ImageFont.truetype(font_path, size)
        except OSError:
            pass
    raise RuntimeError("No TrueType font available; set FONT_PATH to an installed .ttf font")


def read_csv_rows(csv_file):
    with csv_file.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            raise ValueError("CSV must have a header row")
        rows = [{k.strip(): v for k, v in row.items() if k is not None} for row in reader]
        headers = {name.strip() for name in reader.fieldnames}

    field = "lean_angle" if "lean_angle" in headers else "value" if "value" in headers else None
    if field is None:
        raise ValueError("CSV must contain a 'lean_angle' or 'value' column")
    if not rows:
        raise ValueError("CSV has no data rows")

    has_frame = "frame" in headers
    values = {}
    for index, row in enumerate(rows):
        frame = int(row["frame"]) if has_frame else index
        if frame < 0 or frame in values:
            raise ValueError(f"Invalid or duplicate frame number: {frame}")
        angle = float(row[field])
        if not math.isfinite(angle):
            raise ValueError(f"Non-finite lean angle at frame {frame}")
        values[frame] = max(-90.0, min(90.0, angle))
    return values


def draw_frame(output_file, angle, width, height, aa, font):
    """Same drawing pipeline as the previous AA/0-tick/progress script."""
    canvas = Image.new("RGBA", (width * aa, height * aa), (0, 0, 0, 0))
    draw = ImageDraw.Draw(canvas)

    cx = width * 0.5 * aa
    cy = height * 0.52 * aa
    radius = min(width * 0.34, height * 0.28) * aa

    size_scale = min(width / WIDTH, height / HEIGHT)
    draw.arc(
        (cx - radius, cy - radius, cx + radius, cy + radius),
        start=180,
        end=360,
        fill=ARC_COLOR,
        width=max(1, round(ARC_WIDTH * aa * size_scale)),
    )

    radians = math.radians(270 + angle)
    dot_x = cx + radius * math.cos(radians)
    dot_y = cy + radius * math.sin(radians)
    dot_radius = DOT_RADIUS * aa * size_scale
    draw.ellipse(
        (dot_x - dot_radius, dot_y - dot_radius,
         dot_x + dot_radius, dot_y + dot_radius),
        fill=DOT_COLOR,
    )

    apex_y = cy - radius
    tick_length = ZERO_TICK_LENGTH * aa * size_scale
    tick_width = max(1, round(ZERO_TICK_WIDTH * aa * size_scale))
    draw.line(
        [(cx, apex_y - tick_length * 0.8),
         (cx, apex_y + tick_length * 0.2)],
        fill=DOT_COLOR,
        width=tick_width,
    )

    label = f"{abs(round(angle))}°"
    draw.text(
        (cx, height * 0.73 * aa),
        label,
        font=font,
        fill=TEXT_COLOR,
        anchor="mm",
    )

    if aa > 1:
        canvas = canvas.resize((width, height), resample=Image.Resampling.LANCZOS)
    canvas.save(output_file, format="PNG")


def show_progress(completed, total):
    bar_width = 30
    fraction = completed / total
    filled = round(bar_width * fraction)
    bar = "#" * filled + "-" * (bar_width - filled)
    sys.stdout.write(
        f"\rRendering: [{bar}] {fraction:6.1%} "
        f"({completed:,}/{total:,} frames)"
    )
    sys.stdout.flush()


def frame_tasks(values):
    """Supply every frame in order, holding values for missing frame numbers."""
    current_angle = 0.0
    for frame in range(max(values) + 1):
        if frame in values:
            current_angle = values[frame]
        yield frame, current_angle


def init_worker(output_dir, width, height, aa, backend="skia"):
    """Initialize subprocesses once, with Ctrl+C handled by the parent."""
    # SIGINT is ignored only in workers. The parent stops issuing new work,
    # then lets active frames finish before shutting the pool down.
    if multiprocessing.current_process().name != "MainProcess":
        signal.signal(signal.SIGINT, signal.SIG_IGN)
    global _WORKER_FONT, _WORKER_OUTPUT, _WORKER_WIDTH, _WORKER_HEIGHT, _WORKER_AA
    _WORKER_OUTPUT = output_dir
    _WORKER_WIDTH = width
    _WORKER_HEIGHT = height
    _WORKER_AA = aa
    size = max(1, round(FONT_SIZE * aa * min(width / WIDTH, height / HEIGHT)))
    _WORKER_FONT = load_font(size)
    global _WORKER_SKIA
    _WORKER_SKIA = None
    if backend == "skia":
        from skia_backend import SkiaRenderer
        _WORKER_SKIA = SkiaRenderer(width, height, aa, _WORKER_FONT, sys.modules[__name__])


def render_task(task):
    """Render into a temp file; publish only fully saved PNGs."""
    frame, angle = task
    final_path = _WORKER_OUTPUT / f"lean_{frame:06d}.png"
    fd, temp_name = tempfile.mkstemp(
        prefix=f".{final_path.name}.", suffix=".tmp", dir=_WORKER_OUTPUT
    )
    os.close(fd)
    temp_path = Path(temp_name)
    try:
        if _WORKER_SKIA is not None:
            _WORKER_SKIA.save(temp_path, angle)
        else:
            draw_frame(
                temp_path, angle, _WORKER_WIDTH, _WORKER_HEIGHT, _WORKER_AA,
                _WORKER_FONT,
            )
        os.replace(temp_path, final_path)  # Atomic within the same folder.
    finally:
        temp_path.unlink(missing_ok=True)
    return frame


def valid_frame_png(path, width, height):
    """Verify PNG data and dimensions before skipping a previous render."""
    if not path.is_file():
        return False
    try:
        with Image.open(path) as image:
            if (image.format != "PNG" or image.mode != "RGBA"
                    or image.size != (width, height)):
                return False
            image.verify()  # Checks PNG chunks / checksums.
        return True
    except (OSError, ValueError, SyntaxError):
        return False


def manifest_settings(csv_file, width, height, aa, backend="skia"):
    """Parameters affecting PNG pixels; FPS changes only playback metadata."""
    digest = hashlib.sha256()
    with csv_file.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    settings = {
        "render_version": 1,
        "csv_sha256": digest.hexdigest(),
        "width": width,
        "height": height,
        "aa": aa,
        "font_path": FONT_PATH,
        "font_size": FONT_SIZE,
        "arc_color": list(ARC_COLOR),
        "dot_color": list(DOT_COLOR),
        "text_color": list(TEXT_COLOR),
        "arc_width": ARC_WIDTH,
        "dot_radius": DOT_RADIUS,
        "zero_tick_length": ZERO_TICK_LENGTH,
        "zero_tick_width": ZERO_TICK_WIDTH,
    }
    if backend == "skia":
        import skia
        size = max(1, round(FONT_SIZE * aa * min(width / WIDTH, height / HEIGHT)))
        font = load_font(size)
        settings.update({
            "backend": "skia",
            "backend_version": skia.__version__,
            "skia_render_version": 1,
            "resolved_font_sha256": hashlib.sha256(Path(font.path).read_bytes()).hexdigest(),
        })
    return settings


def atomic_write_text(path, contents):
    """Avoid half-written manifest/info files after a process interruption."""
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(contents)
        os.replace(temp_path, path)
    finally:
        temp_path.unlink(missing_ok=True)


def cleanup_temp_frames(output_dir):
    """Remove leftovers from aborted saves, leaving other files untouched."""
    for file in output_dir.glob(".lean_*.png.*.tmp"):
        if re.fullmatch(r"\.lean_\d{6,}\.png\.[^.]+\.tmp", file.name):
            file.unlink(missing_ok=True)


def prepare_output(output_dir, settings, restart, adopt_existing):
    """Only reuse frames when their source and render settings are known."""
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = output_dir / "render_manifest.json"
    existing_manifest = manifest_path.exists()
    old_frames = list(output_dir.glob("lean_*.png")) if restart or not existing_manifest else []

    if restart:
        # Explicit opt-in: remove only frame files created by this renderer.
        for path in old_frames:
            if re.fullmatch(r"lean_\d{6,}\.png", path.name):
                path.unlink()
        manifest_path.unlink(missing_ok=True)
        (output_dir / "sequence_info.txt").unlink(missing_ok=True)
    elif existing_manifest:
        try:
            previous = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise ValueError(
                "Existing render_manifest.json cannot be read. Use --restart "
                "to regenerate the sequence."
            ) from exc
        if previous != settings:
            raise ValueError(
                "Existing PNGs were generated with different CSV content or "
                "render settings. Use --restart to regenerate safely, or "
                "choose another output folder."
            )
    elif old_frames and not adopt_existing:
        raise ValueError(
            "Existing lean_*.png images have no render manifest (possibly "
            "from an older script). To reuse them, run with --adopt-existing "
            "ONLY if the CSV and visual settings are identical. Otherwise "
            "use --restart or a new output folder."
        )

    cleanup_temp_frames(output_dir)
    atomic_write_text(manifest_path, json.dumps(settings, indent=2) + "\n")


def write_sequence_info(output_dir, total_frames, width, height, fps):
    sequence_info = output_dir / "sequence_info.txt"
    atomic_write_text(
        sequence_info,
        f"Lean-angle image sequence\n"
        f"Intended playback FPS: {fps:g}\n"
        f"Frames: {total_frames}\n"
        f"Duration: {total_frames / fps:.6f} seconds\n"
        f"First frame: lean_000000.png\n"
        f"Last frame: lean_{total_frames - 1:06d}.png\n"
        f"Resolution: {width}x{height}\n"
        "\n"
        "PNG images do not store an FPS. In Apple Motion, import as an Image "
        "Sequence and set its source frame rate to the intended FPS above.\n"
        "The CSV 'frame' column represents frame indices, not seconds.\n",
    )
    return sequence_info


def generate_frames(csv_file, output_dir, width, height, aa, workers, fps,
                    restart=False, adopt_existing=False, backend="skia"):
    if backend not in ("pillow", "skia"):
        raise ValueError("Backend must be pillow or skia")
    if backend == "skia":
        try:
            import skia  # Check dependency before modifying the output folder.
        except ImportError as exc:
            raise ValueError("Skia backend requires: python3 -m pip install -r requirements.txt") from exc
    if width <= 0 or height <= 0:
        raise ValueError("Width and height must be positive")
    if not 1 <= aa <= 8:
        raise ValueError("AA must be between 1 and 8")
    if workers < 1:
        raise ValueError("Workers must be at least 1")
    if not math.isfinite(fps) or not 0 < fps <= 240:
        raise ValueError("FPS must be greater than 0 and at most 240")
    if restart and adopt_existing:
        raise ValueError("Choose --restart OR --adopt-existing, not both")

    values = read_csv_rows(csv_file)
    total_frames = max(values) + 1
    settings = manifest_settings(csv_file, width, height, aa, backend)
    prepare_output(output_dir, settings, restart, adopt_existing)

    print("Rendering Lean Angle Frames")
    print(f"Backend: {backend}")
    print(f"Resolution: {width} x {height} | AA: {aa}x | {fps:g} fps | Workers: {workers}")
    print(f"Output: {output_dir}")
    print("Press Ctrl+C once to stop safely; rerun the same command to resume.")

    # Count only valid, already-finished PNG files. Invalid/corrupt ones are
    # rendered again. Missing frame numbers retain their preceding value.
    completed_frames = set()
    for frame in range(total_frames):
        png = output_dir / f"lean_{frame:06d}.png"
        if valid_frame_png(png, width, height):
            completed_frames.add(frame)
    skipped = len(completed_frames)
    print(f"Found {skipped:,} completed frames; {total_frames - skipped:,} remaining.")
    show_progress(skipped, total_frames)
    start_time = time.perf_counter()

    if skipped < total_frames:
        tasks = (task for task in frame_tasks(values) if task[0] not in completed_frames)
        try:
            if workers == 1:
                # Direct worker mode, with no process startup overhead.
                init_worker(output_dir, width, height, aa, backend)
                completed_now = 0
                for task in tasks:
                    render_task(task)
                    completed_now += 1
                    show_progress(skipped + completed_now, total_frames)
            else:
                # Bound queue size so high AA cannot fill RAM with futures.
                with ProcessPoolExecutor(
                    max_workers=workers,
                    initializer=init_worker,
                    initargs=(output_dir, width, height, aa, backend),
                ) as pool:
                    pending = set()

                    def enqueue_one():
                        try:
                            task = next(tasks)
                        except StopIteration:
                            return False
                        pending.add(pool.submit(render_task, task))
                        return True

                    for _ in range(min(workers * 2, total_frames - skipped)):
                        enqueue_one()

                    completed_now = 0
                    while pending:
                        done, pending = wait(pending, return_when=FIRST_COMPLETED)
                        for future in done:
                            future.result()  # Propagate worker failures.
                            completed_now += 1
                            show_progress(skipped + completed_now, total_frames)
                            enqueue_one()
        except KeyboardInterrupt:
            print("\nStopping: allowing in-progress frames to finish and save...")
            # Exiting the pool context waits for submitted workers. These
            # committed images will be detected on the next run.
            print("Paused. Run the same command later to resume.")
            return False
        finally:
            print()  # Move off the progress bar line.

    seconds = time.perf_counter() - start_time
    sequence_info = write_sequence_info(output_dir, total_frames, width, height, fps)
    print(f"Render complete! {total_frames:,} frames available ({skipped:,} reused) in {seconds:.1f}s.")
    print(f"Playback: {fps:g} fps | Duration: {total_frames / fps:.3f} seconds")
    print(f"Settings saved to: {sequence_info}")
    return True


def main():
    parser = argparse.ArgumentParser(
        description="Render antialiased lean-angle PNGs with Skia and resumable multiprocessing for Apple Motion."
    )
    parser.add_argument("csv_path", help="Path to CSV with 'lean_angle' or 'value' column")
    parser.add_argument("-o", "--output", help="Output folder (default: lean_frames beside CSV)")
    parser.add_argument("--width", type=int, default=WIDTH)
    parser.add_argument("--height", type=int, default=HEIGHT)
    parser.add_argument("--aa", type=int, help=f"Supersampling scale 1-8 (default: {AA} for Skia native antialiasing; {PILLOW_AA} for Pillow)")
    parser.add_argument("--backend", choices=("skia", "pillow"), default="skia",
                        help="Graphics backend (default: skia). Pillow is retained for legacy resumes and comparison.")
    parser.add_argument("--fps", type=float, default=FPS, help="Intended image-sequence playback FPS (default: 30). Set same FPS in Apple Motion.")
    parser.add_argument("--restart", action="store_true", help="Delete this renderer's existing PNG frames and start again")
    parser.add_argument("--adopt-existing", action="store_true", help="Resume older lean PNG files with no manifest; use only if CSV/settings match")
    default_workers = (os.cpu_count() or 1) + 1
    parser.add_argument(
        "--workers", type=int, default=default_workers,
        help=f"Parallel render processes (default: CPU core count + 1 = {default_workers}; "
             "override to reduce memory use)",
    )
    args = parser.parse_args()
    if args.aa is None:
        args.aa = AA if args.backend == "skia" else PILLOW_AA

    csv_file = Path(args.csv_path).expanduser().resolve()
    if not csv_file.is_file():
        parser.error(f"CSV file not found: {csv_file}")
    output_dir = (
        Path(args.output).expanduser().resolve()
        if args.output
        else csv_file.parent / "lean_frames"
    )
    try:
        finished = generate_frames(
            csv_file, output_dir, args.width, args.height, args.aa,
            args.workers, args.fps, args.restart, args.adopt_existing, args.backend,
        )
    except ValueError as exc:
        parser.error(str(exc))
    if not finished:
        sys.exit(130)


if __name__ == "__main__":
    main()
